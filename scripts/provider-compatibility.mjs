#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "crates/omnis-cli/provider-compatibility.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const generatedHeader = "Generated by scripts/provider-compatibility.mjs. Do not edit.";

validateManifest();

const [command = "check", ...args] = process.argv.slice(2);
switch (command) {
  case "generate":
    generate(false);
    break;
  case "check":
    generate(true);
    break;
  case "get":
    getValue(args);
    break;
  case "github-env":
    printGithubEnvironment();
    break;
  case "record-npm":
    recordNpmVersions(args);
    break;
  case "report":
    writeReport(args);
    break;
  default:
    fail(`unknown command: ${command}`);
}

function validateManifest() {
  if (manifest.schema_version !== 1) fail("unsupported manifest schema_version");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(manifest.last_verified)) {
    fail("last_verified must use YYYY-MM-DD");
  }
  if (!Array.isArray(manifest.providers) || manifest.providers.length !== manifest.matrix.providers) {
    fail("matrix.providers must match provider count");
  }
  if (manifest.matrix.cross_provider_paths !== manifest.providers.length * (manifest.providers.length - 1)) {
    fail("matrix.cross_provider_paths must cover every off-diagonal provider pair");
  }

  const ids = new Set();
  for (const provider of manifest.providers) {
    if (!provider.id || ids.has(provider.id)) fail(`invalid or duplicate provider id: ${provider.id}`);
    ids.add(provider.id);
    if (!provider.name || !provider.release_tested?.version || !provider.release_tested?.source) {
      fail(`${provider.id} requires name and release_tested version/source`);
    }
    if (!/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(provider.release_tested.version)) {
      fail(`${provider.id} has invalid release_tested.version`);
    }
    if (!["installed", "synthetic-store"].includes(provider.conformance)) {
      fail(`${provider.id} has invalid conformance mode`);
    }
    if (provider.release_tested.source === "npm" && !provider.release_tested.package) {
      fail(`${provider.id} requires release_tested.package`);
    }
    if (provider.release_tested.source === "github" &&
        (!provider.release_tested.tag || !provider.release_tested.commit)) {
      fail(`${provider.id} requires release_tested tag and commit`);
    }
    if (!provider.docs?.session_source || !provider.docs?.resume || !provider.docs?.notes) {
      fail(`${provider.id} requires documentation fields`);
    }
    if (!provider.website?.id || !provider.website?.logo || !provider.website?.tone) {
      fail(`${provider.id} requires website fields`);
    }
    for (const capability of ["read_index", "clean_start", "continuation"]) {
      const platforms = provider.capabilities?.[capability];
      if (!Array.isArray(platforms) || platforms.some((platform) => !["linux", "macos"].includes(platform))) {
        fail(`${provider.id}.capabilities.${capability} must list supported platforms`);
      }
    }
  }

  const questionIds = new Set();
  for (const question of manifest.continuity_questions ?? []) {
    if (!question.id || questionIds.has(question.id) || !question.prompt || !question.expected) {
      fail(`invalid or duplicate continuity question: ${question.id}`);
    }
    questionIds.add(question.id);
  }
  if (questionIds.size === 0) fail("at least one continuity question is required");
}

function generate(checkOnly) {
  const outputs = [
    [join(root, "crates/omnis-cli/src/provider_compatibility.rs"), renderRust()],
    [join(root, "website/app/providers.generated.ts"), renderWebsite()],
    [join(root, "docs/COMPATIBILITY.md"), renderCompatibilityDocs()],
  ];
  let stale = false;
  for (const [path, content] of outputs) {
    const current = readFile(path);
    if (current === content) continue;
    if (checkOnly) {
      console.error(`stale generated compatibility file: ${path.slice(root.length + 1)}`);
      stale = true;
    } else {
      writeFileSync(path, content);
    }
  }
  if (stale) process.exitCode = 1;
}

function renderRust() {
  const constants = manifest.providers
    .filter((provider) => provider.minimum_version)
    .map((provider) => {
      const name = `MINIMUM_${provider.id.replaceAll("-", "_").toUpperCase()}_VERSION`;
      return `pub(crate) const ${name}: &str = ${JSON.stringify(provider.minimum_version)};`;
    });
  return `// ${generatedHeader}\n\n${constants.join("\n")}\n`;
}

function renderWebsite() {
  const providers = manifest.providers.map((provider) => ({
    id: provider.website.id,
    logo: provider.website.logo,
    name: provider.name,
    same: provider.website.same,
    cross: provider.website.cross,
    signal: provider.website.signal ?? `>= ${provider.minimum_version}`,
    tone: provider.website.tone,
  }));
  return `// ${generatedHeader}\n\nexport const providers = ${JSON.stringify(providers, null, 2)} as const;\n`;
}

function renderCompatibilityDocs() {
  const path = join(root, "docs/COMPATIBILITY.md");
  const current = readFileSync(path, "utf8");
  const start = "<!-- provider-compatibility:start -->";
  const end = "<!-- provider-compatibility:end -->";
  const startIndex = current.indexOf(start);
  const endIndex = current.indexOf(end);
  if (startIndex < 0 || endIndex <= startIndex) {
    fail("docs/COMPATIBILITY.md is missing provider compatibility markers");
  }
  const rows = manifest.providers.map((provider) => {
    const versionSignal = provider.minimum_version
      ? `>= ${provider.minimum_version}`
      : `Official API (tested ${provider.release_tested.version})`;
    return `| ${provider.name} | ${versionSignal} | ${provider.docs.session_source} | ${provider.docs.resume} | ${provider.docs.notes} |`;
  });
  const table = [
    start,
    `Last verified: ${manifest.last_verified}`,
    "",
    "| Provider | Version signal | Session source | Resume interface | Notes |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    end,
  ].join("\n");
  return `${current.slice(0, startIndex)}${table}${current.slice(endIndex + end.length)}`;
}

function getValue([providerId, field]) {
  const provider = manifest.providers.find((item) => item.id === providerId);
  if (!provider) fail(`unknown provider: ${providerId}`);
  const value = field.split(".").reduce((current, key) => current?.[key], provider);
  if (typeof value !== "string") fail(`${providerId}.${field} is not a string`);
  process.stdout.write(`${value}\n`);
}

function printGithubEnvironment() {
  const npmEnvironment = {
    claude: "CLAUDE_CODE_VERSION",
    codex: "CODEX_VERSION",
    opencode: "OPENCODE_VERSION",
    grok: "GROK_VERSION",
  };
  for (const provider of manifest.providers) {
    const name = npmEnvironment[provider.id];
    if (name) console.log(`${name}=${provider.release_tested.version}`);
  }
  const hermes = manifest.providers.find((provider) => provider.id === "hermes");
  console.log(`HERMES_VERSION=${hermes.release_tested.version}`);
  console.log(`HERMES_TAG=${hermes.release_tested.tag}`);
  console.log(`HERMES_COMMIT=${hermes.release_tested.commit}`);
}

function recordNpmVersions([prefix]) {
  if (!prefix) fail("record-npm requires install prefix");
  const output = execFileSync(
    "npm",
    ["--global", "--prefix", prefix, "list", "--depth=0", "--json"],
    { encoding: "utf8" },
  );
  const installed = JSON.parse(output).dependencies ?? {};
  for (const provider of manifest.providers) {
    const packageName = provider.release_tested.package;
    if (!packageName) continue;
    const version = installed[packageName]?.version;
    if (!version) fail(`npm did not report ${packageName}`);
    console.log(`${testedVersionVariable(provider.id)}=${version}`);
    console.log(`${testedVersionSourceVariable(provider.id)}=npm-package-metadata`);
  }
}

function writeReport(arguments_) {
  const options = parseOptions(arguments_);
  const status = options.status ?? process.env.OMNI_COMPAT_CONFORMANCE_STATUS;
  const outputDirectory = options["output-dir"];
  if (!outputDirectory || !["passed", "failed", "not_run"].includes(status)) {
    fail("report requires --status passed|failed|not_run and --output-dir PATH");
  }
  const generatedAt = options["generated-at"] ?? new Date().toISOString();
  if (Number.isNaN(Date.parse(generatedAt))) fail("--generated-at must be an ISO timestamp");

  const providers = manifest.providers.map((provider) => ({
    id: provider.id,
    name: provider.name,
    minimum_version: provider.minimum_version,
    expected: {
      version: provider.release_tested.version,
      source: provider.release_tested.source,
      tag: provider.release_tested.tag ?? null,
      commit: provider.release_tested.commit ?? null,
    },
    observed: observedVersion(provider.id),
    capabilities: provider.capabilities,
    limitations: provider.limitations ?? [],
    conformance_mode: provider.conformance,
    matrix_conformance: status,
    authenticated_marker_canary: canaryStatus(provider),
  }));
  const report = {
    schema_version: 1,
    generated_at: generatedAt,
    manifest_last_verified: manifest.last_verified,
    matrix: manifest.matrix,
    status,
    providers,
  };
  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(join(outputDirectory, "provider-compatibility.json"), `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(join(outputDirectory, "provider-compatibility.md"), renderReportMarkdown(report));

  if (status === "failed") {
    console.log("::warning::Provider compatibility conformance failed. Inspect uploaded dashboard artifact.");
  } else if (status === "not_run") {
    console.log("::warning::Provider compatibility conformance did not run. Inspect uploaded dashboard artifact.");
  }
  for (const provider of providers) {
    if (["failed", "error"].includes(provider.authenticated_marker_canary)) {
      console.log(`::warning::${provider.name} authenticated marker canary failed.`);
    }
  }
}

function renderReportMarkdown(report) {
  const rows = report.providers.map((provider) => {
    const minimum = provider.minimum_version ? `>= ${provider.minimum_version}` : "official API";
    const observed = provider.observed.version ?? "not recorded";
    const observedSource = provider.observed.source ?? "not recorded";
    const expectedRevision = formatRevision(provider.expected);
    const observedRevision = formatRevision(provider.observed);
    return `| ${provider.name} | ${minimum} | ${provider.expected.version} | ${expectedRevision} | ${observed} | ${provider.observed.status} | ${observedSource} | ${observedRevision} | ${provider.conformance_mode} | ${formatPlatforms(provider.capabilities.read_index)} | ${formatPlatforms(provider.capabilities.clean_start)} | ${formatPlatforms(provider.capabilities.continuation)} | ${provider.matrix_conformance} | ${provider.authenticated_marker_canary} |`;
  });
  return [
    "# Provider compatibility dashboard",
    "",
    `Generated: ${report.generated_at}`,
    "",
    `Cross-provider matrix: ${report.matrix.cross_provider_paths} paths across ${report.matrix.providers} providers`,
    "",
    "| Provider | Native gate | Expected/pinned version | Expected revision | Observed version | Observation status | Observed source | Observed revision | Test mode | Read/index | Clean start | Continue/import | Matrix conformance | Authenticated marker canary |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "Authenticated marker canaries are opt-in and never required by normal CI.",
    "",
  ].join("\n");
}

function formatPlatforms(platforms) {
  if (platforms.length === 0) return "Not guaranteed";
  return platforms.map((platform) => platform === "macos" ? "macOS" : "Linux").join(", ");
}

function parseOptions(arguments_) {
  const options = {};
  for (let index = 0; index < arguments_.length; index += 2) {
    const name = arguments_[index];
    const value = arguments_[index + 1];
    if (!name?.startsWith("--") || value === undefined) fail(`invalid option: ${name}`);
    options[name.slice(2)] = value;
  }
  return options;
}

function testedVersionVariable(providerId) {
  return `OMNI_COMPAT_TESTED_${environmentKey(providerId)}`;
}

function testedVersionSourceVariable(providerId) {
  return `OMNI_COMPAT_TESTED_SOURCE_${environmentKey(providerId)}`;
}

function testedTagVariable(providerId) {
  return `OMNI_COMPAT_TESTED_TAG_${environmentKey(providerId)}`;
}

function testedCommitVariable(providerId) {
  return `OMNI_COMPAT_TESTED_COMMIT_${environmentKey(providerId)}`;
}

function observedVersion(providerId) {
  const version = process.env[testedVersionVariable(providerId)];
  const tag = process.env[testedTagVariable(providerId)] ?? null;
  const commit = process.env[testedCommitVariable(providerId)] ?? null;
  validateRevision(providerId, tag, commit);
  if (!version) {
    return { status: "not recorded", version: null, source: null, tag, commit };
  }
  if (!/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(version)) {
    fail(`${providerId} has invalid observed version`);
  }
  return {
    status: "recorded",
    version,
    source: process.env[testedVersionSourceVariable(providerId)] ?? "workflow",
    tag,
    commit,
  };
}

function formatRevision(revision) {
  if (!revision.tag && !revision.commit) return "not recorded";
  if (!revision.tag) return revision.commit;
  if (!revision.commit) return revision.tag;
  return `${revision.tag} @ ${revision.commit.slice(0, 12)}`;
}

function validateRevision(providerId, tag, commit) {
  if (tag && !/^[0-9A-Za-z][0-9A-Za-z._+-]*$/.test(tag)) {
    fail(`${providerId} has invalid observed tag`);
  }
  if (commit && !/^[0-9a-f]{40}$/.test(commit)) {
    fail(`${providerId} has invalid observed commit`);
  }
}

function canaryStatus(provider) {
  if (!provider.authenticated_canary) return "not_available";
  const status = process.env[`OMNI_COMPAT_CANARY_${environmentKey(provider.id)}`] ?? "not_run";
  if (!["passed", "failed", "error", "not_run"].includes(status)) {
    fail(`${provider.id} authenticated canary status is invalid: ${status}`);
  }
  return status;
}

function environmentKey(providerId) {
  return providerId.replaceAll("-", "_").toUpperCase();
}

function readFile(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}
