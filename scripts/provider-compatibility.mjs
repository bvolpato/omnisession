#!/usr/bin/env node

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "crates/omnis-cli/provider-compatibility.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const generatedHeader = "Generated by scripts/provider-compatibility.mjs. Do not edit.";
const platforms = ["linux", "macos", "windows"];
const evidenceTiers = [
  "source-ci",
  "synthetic-store",
  "installed-token-free",
  "authenticated-canary",
  "not-run",
];
const conformanceStatuses = ["passed", "failed", "not_run"];
const capabilityKeys = [
  "read_index",
  "clean_start",
  "same_provider_resume",
  "cross_provider_import",
];
const rustProviderVariants = {
  antigravity: "Antigravity",
  claude: "Claude",
  codex: "Codex",
  "cursor-agent": "CursorCli",
  "cursor-ide": "CursorIde",
  grok: "Grok",
  hermes: "Hermes",
  opencode: "OpenCode",
  pi: "Pi",
};
const rustCapabilityVariants = {
  read_index: "ReadIndex",
  clean_start: "CleanStart",
  same_provider_resume: "SameProviderResume",
  cross_provider_import: "CrossProviderImport",
};

validateManifest();
const providers = manifest.provider_priority.map((id) =>
  manifest.providers.find((provider) => provider.id === id),
);

const [command = "check", ...args] = process.argv.slice(2);
switch (command) {
  case "generate":
    generate(false);
    break;
  case "check":
    generate(true);
    break;
  case "get":
    getValue(args);
    break;
  case "github-env":
    printGithubEnvironment();
    break;
  case "record-npm":
    recordNpmVersions(args);
    break;
  case "report":
    writeReport(args);
    break;
  default:
    fail(`unknown command: ${command}`);
}

function validateManifest() {
  if (manifest.schema_version !== 3) fail("unsupported manifest schema_version");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(manifest.last_verified)) {
    fail("last_verified must use YYYY-MM-DD");
  }
  if (!Array.isArray(manifest.providers) || manifest.providers.length !== manifest.matrix.providers) {
    fail("matrix.providers must match provider count");
  }
  if (manifest.matrix.cross_provider_paths !== manifest.providers.length * (manifest.providers.length - 1)) {
    fail("matrix.cross_provider_paths must cover every off-diagonal provider pair");
  }

  const ids = new Set();
  for (const provider of manifest.providers) {
    if (!provider.id || ids.has(provider.id)) fail(`invalid or duplicate provider id: ${provider.id}`);
    ids.add(provider.id);
    if (!provider.name || !provider.release_tested?.version || !provider.release_tested?.source) {
      fail(`${provider.id} requires name and release_tested version/source`);
    }
    if (!/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(provider.release_tested.version)) {
      fail(`${provider.id} has invalid release_tested.version`);
    }
    if (!["installed", "synthetic-store"].includes(provider.conformance)) {
      fail(`${provider.id} has invalid conformance mode`);
    }
    if (provider.release_tested.source === "npm" && !provider.release_tested.package) {
      fail(`${provider.id} requires release_tested.package`);
    }
    if (provider.release_tested.source === "github" &&
        (!provider.release_tested.tag || !provider.release_tested.commit)) {
      fail(`${provider.id} requires release_tested tag and commit`);
    }
    if (!provider.docs?.session_source || !provider.docs?.resume || !provider.docs?.notes) {
      fail(`${provider.id} requires documentation fields`);
    }
    if (!provider.website?.id || !provider.website?.logo || !provider.website?.tone) {
      fail(`${provider.id} requires website fields`);
    }
    const declaredCapabilities = Object.keys(provider.capabilities ?? {}).sort();
    if (declaredCapabilities.join(",") !== [...capabilityKeys].sort().join(",")) {
      fail(`${provider.id}.capabilities must declare ${capabilityKeys.join(", ")}`);
    }
    for (const capability of capabilityKeys) {
      const capabilityPlatforms = provider.capabilities?.[capability];
      if (!Array.isArray(capabilityPlatforms) ||
          capabilityPlatforms.some((platform) => !platforms.includes(platform)) ||
          new Set(capabilityPlatforms).size !== capabilityPlatforms.length) {
        fail(`${provider.id}.capabilities.${capability} must list supported platforms`);
      }
    }
    for (const platform of platforms) {
      validateEvidence(
        `${provider.id}.platform_evidence.${platform}`,
        provider.platform_evidence?.[platform],
        false,
      );
    }
  }

  if (!Array.isArray(manifest.provider_priority) ||
      manifest.provider_priority.length !== ids.size ||
      new Set(manifest.provider_priority).size !== ids.size ||
      manifest.provider_priority.some((id) => !ids.has(id))) {
    fail("provider_priority must list every provider exactly once");
  }

  const questionIds = new Set();
  for (const question of manifest.continuity_questions ?? []) {
    if (!question.id || questionIds.has(question.id) || !question.prompt || !question.expected) {
      fail(`invalid or duplicate continuity question: ${question.id}`);
    }
    questionIds.add(question.id);
  }
  if (questionIds.size === 0) fail("at least one continuity question is required");
}

function generate(checkOnly) {
  const outputs = [
    [join(root, "crates/omnis-cli/src/provider_compatibility.rs"), renderRust()],
    [join(root, "website/app/providers.generated.ts"), renderWebsite()],
    [join(root, "docs/COMPATIBILITY.md"), renderCompatibilityDocs()],
  ];
  let stale = false;
  for (const [path, content] of outputs) {
    const current = readFile(path)?.replaceAll("\r\n", "\n");
    if (current === content) continue;
    if (checkOnly) {
      console.error(`stale generated compatibility file: ${path.slice(root.length + 1)}`);
      stale = true;
    } else {
      writeFileSync(path, content);
    }
  }
  if (stale) process.exitCode = 1;
}

function renderRust() {
  const constants = providers
    .filter((provider) => provider.minimum_version)
    .map((provider) => {
      const name = `MINIMUM_${provider.id.replaceAll("-", "_").toUpperCase()}_VERSION`;
      return `pub(crate) const ${name}: &str = ${JSON.stringify(provider.minimum_version)};`;
    });
  const priority = providers
    .map((provider) => `    Provider::${rustProviderVariant(provider.id)},`)
    .join("\n");
  const capabilityEntries = providers.flatMap((provider) =>
    capabilityKeys.map((capability) => {
      const mask = provider.capabilities[capability].reduce(
        (value, platform) => value | (1 << platforms.indexOf(platform)),
        0,
      );
      return `        (Provider::${rustProviderVariant(provider.id)}, ${rustCapabilityVariants[capability]}) => ${mask},`;
    }),
  );
  return `// ${generatedHeader}

use omnis_ir::Provider;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Capability {
    ReadIndex,
    CleanStart,
    SameProviderResume,
    CrossProviderImport,
}

#[allow(dead_code)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Platform {
    Linux,
    Macos,
    Windows,
}

#[cfg(target_os = "linux")]
pub(crate) const CURRENT_PLATFORM: Option<Platform> = Some(Platform::Linux);
#[cfg(target_os = "macos")]
pub(crate) const CURRENT_PLATFORM: Option<Platform> = Some(Platform::Macos);
#[cfg(target_os = "windows")]
pub(crate) const CURRENT_PLATFORM: Option<Platform> = Some(Platform::Windows);
#[cfg(not(any(target_os = "linux", target_os = "macos", target_os = "windows")))]
pub(crate) const CURRENT_PLATFORM: Option<Platform> = None;

pub(crate) const PROVIDER_PRIORITY: [Provider; ${providers.length}] = [
${priority}
];

pub(crate) const fn supports_capability_on(
    provider: Provider,
    capability: Capability,
    platform: Platform,
) -> bool {
    use Capability::{CleanStart, CrossProviderImport, ReadIndex, SameProviderResume};

    #[allow(clippy::match_same_arms)]
    let platform_mask = match (provider, capability) {
${capabilityEntries.join("\n")}
        _ => 0,
    };
    let bit = match platform {
        Platform::Linux => 1,
        Platform::Macos => 2,
        Platform::Windows => 4,
    };
    platform_mask & bit != 0
}

pub(crate) const fn supports_capability(provider: Provider, capability: Capability) -> bool {
    match CURRENT_PLATFORM {
        Some(platform) => supports_capability_on(provider, capability, platform),
        None => false,
    }
}

${constants.join("\n")}
`;
}

function renderWebsite() {
  const websiteProviders = providers.map((provider) => ({
    id: provider.website.id,
    logo: provider.website.logo,
    name: provider.name,
    same: provider.website.same,
    cross: provider.website.cross,
    signal: provider.website.signal ?? `>= ${provider.minimum_version}`,
    tone: provider.website.tone,
    capabilities: provider.capabilities,
    platformEvidence: provider.platform_evidence,
  }));
  return `// ${generatedHeader}\n\nexport const providers = ${JSON.stringify(websiteProviders, null, 2)} as const;\n`;
}

function renderCompatibilityDocs() {
  const path = join(root, "docs/COMPATIBILITY.md");
  const current = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
  const start = "<!-- provider-compatibility:start -->";
  const end = "<!-- provider-compatibility:end -->";
  const startIndex = current.indexOf(start);
  const endIndex = current.indexOf(end);
  if (startIndex < 0 || endIndex <= startIndex) {
    fail("docs/COMPATIBILITY.md is missing provider compatibility markers");
  }
  const rows = providers.map((provider) => {
    const versionSignal = provider.minimum_version
      ? `>= ${provider.minimum_version}`
      : `Official API (tested ${provider.release_tested.version})`;
    return `| ${provider.name} | ${versionSignal} | ${provider.docs.session_source} | ${provider.docs.resume} | ${formatPlatforms(provider.capabilities.read_index)} | ${formatPlatforms(provider.capabilities.clean_start)} | ${formatPlatforms(provider.capabilities.same_provider_resume)} | ${formatPlatforms(provider.capabilities.cross_provider_import)} | ${provider.docs.notes} | ${formatPlatformEvidence(provider.platform_evidence)} |`;
  });
  const table = [
    start,
    `Last verified: ${manifest.last_verified}`,
    "",
    "| Provider | Version signal | Session source | Resume interface | Read/index | Clean start | Same-provider resume | Cross-provider import | Notes | Validation evidence |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    end,
  ].join("\n");
  return `${current.slice(0, startIndex)}${table}${current.slice(endIndex + end.length)}`;
}

function getValue([providerId, field]) {
  const provider = manifest.providers.find((item) => item.id === providerId);
  if (!provider) fail(`unknown provider: ${providerId}`);
  const value = field.split(".").reduce((current, key) => current?.[key], provider);
  if (typeof value !== "string") fail(`${providerId}.${field} is not a string`);
  process.stdout.write(`${value}\n`);
}

function printGithubEnvironment() {
  const npmEnvironment = {
    claude: "CLAUDE_CODE_VERSION",
    codex: "CODEX_VERSION",
    opencode: "OPENCODE_VERSION",
    grok: "GROK_VERSION",
  };
  for (const provider of manifest.providers) {
    const name = npmEnvironment[provider.id];
    if (name) console.log(`${name}=${provider.release_tested.version}`);
  }
  const hermes = manifest.providers.find((provider) => provider.id === "hermes");
  console.log(`HERMES_VERSION=${hermes.release_tested.version}`);
  console.log(`HERMES_TAG=${hermes.release_tested.tag}`);
  console.log(`HERMES_COMMIT=${hermes.release_tested.commit}`);
}

function recordNpmVersions([prefix]) {
  if (!prefix) fail("record-npm requires install prefix");
  for (const provider of manifest.providers) {
    const packageName = provider.release_tested.package;
    if (!packageName) continue;
    const metadataCandidates = [
      join(prefix, "node_modules", packageName, "package.json"),
      join(prefix, "lib", "node_modules", packageName, "package.json"),
    ].filter((path) => readFile(path) !== null);
    if (metadataCandidates.length !== 1) {
      fail(`npm package metadata missing or ambiguous for ${packageName}`);
    }
    const metadata = readFileSync(metadataCandidates[0], "utf8");
    let installed;
    try {
      installed = JSON.parse(metadata);
    } catch {
      fail(`npm package metadata is invalid for ${packageName}`);
    }
    if (installed.name !== packageName || !installed.version) {
      fail(`npm package metadata does not identify ${packageName}`);
    }
    const version = installed.version;
    console.log(`${testedVersionVariable(provider.id)}=${version}`);
    console.log(`${testedVersionSourceVariable(provider.id)}=npm-package-metadata`);
  }
}

function writeReport(arguments_) {
  const options = parseOptions(arguments_);
  const status = options.status ?? process.env.OMNI_COMPAT_CONFORMANCE_STATUS;
  const matrixStatus = options["matrix-status"];
  const adapterStatus = options["adapter-status"];
  const outputDirectory = options["output-dir"];
  if (!outputDirectory || !conformanceStatuses.includes(status) ||
      !conformanceStatuses.includes(matrixStatus) ||
      !conformanceStatuses.includes(adapterStatus)) {
    fail("report requires --status, --matrix-status, and --adapter-status as passed|failed|not_run plus --output-dir PATH");
  }
  const generatedAt = options["generated-at"] ?? new Date().toISOString();
  if (Number.isNaN(Date.parse(generatedAt))) fail("--generated-at must be an ISO timestamp");
  const platform = options.platform ?? currentPlatform();
  if (!platforms.includes(platform)) fail("--platform must be linux|macos|windows");

  const reportProviders = providers.map((provider) => {
    const canary = canaryStatus(provider);
    const observed = observedVersion(provider.id);
    const installedConformance = installedTokenFreeConformance(provider);
    const evidence = observedEvidence(provider, canary, observed, installedConformance);
    return {
      id: provider.id,
      name: provider.name,
      minimum_version: provider.minimum_version,
      expected: {
        version: provider.release_tested.version,
        source: provider.release_tested.source,
        tag: provider.release_tested.tag ?? null,
        commit: provider.release_tested.commit ?? null,
      },
      observed,
      capabilities: provider.capabilities,
      limitations: provider.limitations ?? [],
      conformance_mode: provider.conformance,
      platform,
      declared_evidence: provider.platform_evidence[platform],
      observed_evidence: evidence,
      matrix_conformance: matrixStatus,
      installed_token_free_conformance: installedConformance,
      authenticated_marker_canary: canary,
    };
  });
  const report = {
    schema_version: 3,
    generated_at: generatedAt,
    manifest_last_verified: manifest.last_verified,
    platform,
    matrix: manifest.matrix,
    status,
    matrix_status: matrixStatus,
    adapter_status: adapterStatus,
    providers: reportProviders,
  };
  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(join(outputDirectory, "provider-compatibility.json"), `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(join(outputDirectory, "provider-compatibility.md"), renderReportMarkdown(report));

  if (status === "failed") {
    console.log("::warning::Provider compatibility conformance failed. Inspect uploaded dashboard artifact.");
  } else if (status === "not_run") {
    console.log("::warning::Provider compatibility conformance did not run. Inspect uploaded dashboard artifact.");
  }
  for (const provider of reportProviders) {
    if (["failed", "error"].includes(provider.authenticated_marker_canary)) {
      console.log(`::warning::${provider.name} authenticated marker canary failed.`);
    }
  }
}

function renderReportMarkdown(report) {
  const rows = report.providers.map((provider) => {
    const minimum = provider.minimum_version ? `>= ${provider.minimum_version}` : "official API";
    const observed = provider.observed.version ?? "not recorded";
    const observedSource = provider.observed.source ?? "not recorded";
    const expectedRevision = formatRevision(provider.expected);
    const observedRevision = formatRevision(provider.observed);
    return `| ${provider.name} | ${minimum} | ${provider.expected.version} | ${expectedRevision} | ${observed} | ${provider.observed.status} | ${observedSource} | ${observedRevision} | ${provider.conformance_mode} | ${provider.declared_evidence.join(", ")} | ${provider.observed_evidence.join(", ")} | ${formatPlatforms(provider.capabilities.read_index)} | ${formatPlatforms(provider.capabilities.clean_start)} | ${formatPlatforms(provider.capabilities.same_provider_resume)} | ${formatPlatforms(provider.capabilities.cross_provider_import)} | ${provider.matrix_conformance} | ${provider.installed_token_free_conformance} | ${provider.authenticated_marker_canary} |`;
  });
  return [
    "# Provider compatibility dashboard",
    "",
    `Generated: ${report.generated_at}`,
    "",
    `Platform: ${formatPlatform(report.platform)}`,
    "",
    `Cross-provider matrix: ${report.matrix.cross_provider_paths} paths across ${report.matrix.providers} providers`,
    "",
    `Matrix conformance: ${report.matrix_status}`,
    "",
    `Adapter/store conformance: ${report.adapter_status}`,
    "",
    "| Provider | Native gate | Expected/pinned version | Expected revision | Observed version | Observation status | Observed source | Observed revision | Test mode | Declared evidence | Observed evidence | Read/index | Clean start | Same-provider resume | Cross-provider import | Matrix conformance | Installed token-free | Authenticated marker canary |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "Evidence records validation performed on this platform. It does not expand declared platform capabilities.",
    "",
    "Authenticated marker canaries are opt-in and never required by normal CI.",
    "",
  ].join("\n");
}

function formatPlatforms(platforms) {
  if (platforms.length === 0) return "Not guaranteed";
  return platforms.map(formatPlatform).join(", ");
}

function formatPlatform(platform) {
  return platform === "macos" ? "macOS" : `${platform[0].toUpperCase()}${platform.slice(1)}`;
}

function formatPlatformEvidence(platformEvidence) {
  return platforms
    .map((platform) => `${formatPlatform(platform)}: ${platformEvidence[platform].join(" + ")}`)
    .join("<br>");
}

function parseOptions(arguments_) {
  const options = {};
  for (let index = 0; index < arguments_.length; index += 2) {
    const name = arguments_[index];
    const value = arguments_[index + 1];
    if (!name?.startsWith("--") || value === undefined) fail(`invalid option: ${name}`);
    options[name.slice(2)] = value;
  }
  return options;
}

function testedVersionVariable(providerId) {
  return `OMNI_COMPAT_TESTED_${environmentKey(providerId)}`;
}

function testedVersionSourceVariable(providerId) {
  return `OMNI_COMPAT_TESTED_SOURCE_${environmentKey(providerId)}`;
}

function testedTagVariable(providerId) {
  return `OMNI_COMPAT_TESTED_TAG_${environmentKey(providerId)}`;
}

function testedCommitVariable(providerId) {
  return `OMNI_COMPAT_TESTED_COMMIT_${environmentKey(providerId)}`;
}

function observedVersion(providerId) {
  const version = process.env[testedVersionVariable(providerId)];
  const tag = process.env[testedTagVariable(providerId)] ?? null;
  const commit = process.env[testedCommitVariable(providerId)] ?? null;
  validateRevision(providerId, tag, commit);
  if (!version) {
    return { status: "not recorded", version: null, source: null, tag, commit };
  }
  if (!/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(version)) {
    fail(`${providerId} has invalid observed version`);
  }
  return {
    status: "recorded",
    version,
    source: process.env[testedVersionSourceVariable(providerId)] ?? "workflow",
    tag,
    commit,
  };
}

function formatRevision(revision) {
  if (!revision.tag && !revision.commit) return "not recorded";
  if (!revision.tag) return revision.commit;
  if (!revision.commit) return revision.tag;
  return `${revision.tag} @ ${revision.commit.slice(0, 12)}`;
}

function validateRevision(providerId, tag, commit) {
  if (tag && !/^[0-9A-Za-z][0-9A-Za-z._+-]*$/.test(tag)) {
    fail(`${providerId} has invalid observed tag`);
  }
  if (commit && !/^[0-9a-f]{40}$/.test(commit)) {
    fail(`${providerId} has invalid observed commit`);
  }
}

function canaryStatus(provider) {
  if (!provider.authenticated_canary) return "not_available";
  const status = process.env[`OMNI_COMPAT_CANARY_${environmentKey(provider.id)}`] ?? "not_run";
  if (!["passed", "failed", "error", "not_run"].includes(status)) {
    fail(`${provider.id} authenticated canary status is invalid: ${status}`);
  }
  return status;
}

function installedTokenFreeConformance(provider) {
  const name = `OMNI_COMPAT_INSTALLED_${environmentKey(provider.id)}`;
  const defaultStatus = provider.conformance === "installed" ? "not_run" : "not_available";
  const status = process.env[name] ?? defaultStatus;
  if (![...conformanceStatuses, "not_available"].includes(status)) {
    fail(`${provider.id} installed token-free conformance status is invalid: ${status}`);
  }
  if (provider.conformance !== "installed" && status !== "not_available") {
    fail(`${provider.id} does not support installed token-free conformance`);
  }
  return status;
}

function observedEvidence(provider, canary, observed, installedConformance) {
  const name = `OMNI_COMPAT_EVIDENCE_${environmentKey(provider.id)}`;
  const value = process.env[name];
  const evidence = value ? value.split(",").map((item) => item.trim()).filter(Boolean) : ["not-run"];
  if (canary === "passed" && !evidence.includes("authenticated-canary")) {
    if (evidence.includes("not-run")) evidence.length = 0;
    evidence.push("authenticated-canary");
  }
  validateEvidence(name, evidence, true);
  if (evidence.includes("authenticated-canary") && canary !== "passed") {
    fail(`${provider.id} authenticated-canary evidence requires a passed canary`);
  }
  const hasInstalledEvidence = evidence.includes("installed-token-free");
  if (hasInstalledEvidence && observed.status !== "recorded") {
    fail(`${provider.id} installed-token-free evidence requires an observed version`);
  }
  if (hasInstalledEvidence && installedConformance !== "passed") {
    fail(`${provider.id} installed-token-free evidence requires passed conformance`);
  }
  if (installedConformance === "passed" && !hasInstalledEvidence) {
    fail(`${provider.id} passed installed token-free conformance requires matching evidence`);
  }
  return evidence;
}

function validateEvidence(name, evidence, allowNotRun) {
  if (!Array.isArray(evidence) || evidence.length === 0 ||
      evidence.some((item) => !evidenceTiers.includes(item)) ||
      new Set(evidence).size !== evidence.length) {
    fail(`${name} must list unique evidence tiers`);
  }
  if ((!allowNotRun && evidence.includes("not-run")) ||
      (evidence.includes("not-run") && evidence.length !== 1)) {
    fail(`${name} has invalid not-run evidence`);
  }
}

function currentPlatform() {
  const normalized = { darwin: "macos", win32: "windows" }[process.platform] ?? process.platform;
  if (!platforms.includes(normalized)) {
    fail(`unsupported report platform: ${process.platform}; pass --platform explicitly`);
  }
  return normalized;
}

function environmentKey(providerId) {
  return providerId.replaceAll("-", "_").toUpperCase();
}

function rustProviderVariant(providerId) {
  const variant = rustProviderVariants[providerId];
  if (!variant) fail(`provider ${providerId} has no Rust variant mapping`);
  return variant;
}

function readFile(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}
